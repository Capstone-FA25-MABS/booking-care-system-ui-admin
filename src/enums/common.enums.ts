/**
 * Represents the status of an entity.
 */
export enum Status {
    /**
     * The entity is active.
     */
    ACTIVE,

    /**
     * The entity is inactive.
     */
    INACTIVE,
}

/**
 * Represents the gender of a person.
 */
export enum Gender {
    /**
     * Male gender.
     */
    MALE,

    /**
     * Female gender.
     */
    FEMALE,

    /**
     * Other or unspecified gender.
     */
    OTHER,
}
